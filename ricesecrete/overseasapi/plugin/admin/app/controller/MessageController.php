<?php

namespace plugin\admin\app\controller;

use app\model\user\UserModel;
use app\services\UserServices;
use plugin\admin\app\model\Admin;
use plugin\admin\app\model\Content;
use plugin\admin\app\model\Dict;
use plugin\admin\app\model\Message;
use plugin\admin\app\services\MessageServices;
use support\exception\BusinessException;
use support\Request;
use support\Response;
use Throwable;

/**
 * 站内信管理
 */
class MessageController extends Crud
{

    /**
     * @var Content
     */
    protected $model = null;

    /**
     * 构造函数
     * @return void
     */
    public function __construct()
    {
        $this->model = new Message();
    }

    /**
     * 浏览
     * @return Response
     * @throws Throwable
     */
    public function index(): Response
    {

        return raw_view('message/index');
    }

    /**
     * 查询
     * @param Request $request
     * @return Response
     */
    public function select(Request $request): Response
    {
//        print_r($request->path());
        [$where, $format, $limit, $field, $order] = $this->selectInput($request);
        if ($request->get('order', '') == '') {
            $order = 'desc';
        }
        if (empty($field)) {
            $field = "id";
        }
        $username = $request->get('username', '');
        if (!empty($username)) {
            $ids = UserModel::where('username', 'like', '%' . $username . '%')->column('id');
            if (!empty($ids)) {
                $where['user_id'][0] = 'in';
                $where['user_id'][1] = $ids;
            } else {
                $where['user_id'] = 0;
            }
            unset($where['username']);
        }
        $query = $this->doSelect($where, $field, $order);
        $methods = [
            'select' => 'formatSelect',
            'tree' => 'formatTree',
            'table_tree' => 'formatTableTree',
            'normal' => 'formatNormal',
        ];
        $paginator = $query->paginate($limit);
        $total = $paginator->total();
        $items = $paginator->items();
        $messagetype = Dict::get('messagetype');
        $message_arr = [];
        foreach ($messagetype as $item) {
            $message_arr[(int)$item['value']] = $item['name'];
        }
        foreach ($items as &$item) {
            $item['user_info'] = UserServices::getUserInfo($item['user_id']);
            $admin_info = [
                'id' => 0,
                'username' => '系统消息',
            ];
            $item['admin_info'] = empty($item['admin_id']) ? $admin_info : Admin::where('id', $item['admin_id'])->field(['id', 'username'])->find();
            //类型
            $item['type_str'] = $message_arr[$item['type']];

            $item['read_at'] = empty($item['read_at']) ? '' : $item['read_at'];
        }
        // TODO: Change the autogenerated stub
        return call_user_func([$this, $methods[$format]], $items, $total);
    }

    /**
     * 插入
     * @param Request $request
     * @return Response
     * @throws BusinessException|Throwable
     */
    public function insert(Request $request): Response
    {
        if ($request->method() === 'POST') {
            $data = $this->insertInput($request);
            $data['is_pop'] = 0;//默认不弹窗
            $send_type = $request->post('send_type', '1');
            $user_ids = [];
            if ($send_type == '1') {
                $level_ids = [$request->post('level', '')];
                $level_ids = array_filter($level_ids);
                $user_name_str = $request->post('user_names', '');
                $user_names = [];
                if (!empty($user_name_str)) {
                    $user_names = explode(',', $user_name_str);
                    //去除空数组
                    $user_names = array_filter($user_names);
                }
                if (!empty($level_ids) && !empty($user_names)) {
                    $user_ids = UserModel::whereIn('level', $level_ids)->whereIn('username', $user_names)->column('id');
                }
                if (empty($level_ids) && !empty($user_names)) {
                    $user_ids = UserModel::whereIn('username', $user_names)->column('id');
                }
                if (!empty($level_ids) && empty($user_names)) {
                    $user_ids = UserModel::whereIn('level', $level_ids)->column('id');
                }
            } else {
                $user_name = $request->post('user_name', '');
                $user_id = UserModel::where('username', $user_name)->value('id');
                if (!empty($user_id)) {
                    $user_ids = UserModel::where('leader0', $user_id)->whereOr('leader1', $user_id)->where('id', '<>', $user_id)->column('id');
                    echo UserModel::getLastSql();
                }
            }
            if (empty($user_ids)) {
                return json([
                    'code' => 1,
                    'msg' => '没有可发送的用户',
                ]);
            }
            $admin_id = admin_id();
            $ret = MessageServices::addMessage($user_ids, $admin_id, $data['title'], $data['content'], $data['is_pop']);
            if (!$ret) {
                return json([
                    'code' => 1,
                    'msg' => '发送失败',
                ]);
            }
            return json([
                'code' => 0,
                'msg' => '成功',
            ]);
        }
        return raw_view('message/insert');
    }

    /**
     * 更新
     * @param Request $request
     * @return Response
     * @throws BusinessException|Throwable
     */
    public function update(Request $request): Response
    {
        if ($request->method() === 'POST') {
//            return parent::update($request);
            return json([
                'code' => 0,
                'msg' => 'success',
            ]);
        }
        return raw_view('message/update');
    }

}
