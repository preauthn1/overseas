<?php

namespace plugin\admin\app\controller;

use app\model\user\UserBillModel;
use app\model\user\UserModel;
use app\services\UserBillServices;
use app\services\UserServices;
use plugin\admin\app\model\User;
use support\Request;
use support\Response;
use Throwable;

/**
 * 用户流水管理
 */
class UserBillController extends Crud
{

    /**
     * @var User
     */
    protected $model = null;

    /**
     * 构造函数
     * @return void
     */
    public function __construct()
    {
        $this->model = new UserBillModel();
    }

    /**
     * 查询
     * @param Request $request
     * @return Response
     * @throws \Exception
     */
    public function select(Request $request): Response
    {
        [$where, $format, $limit, $field, $order, $page] = $this->selectInput($request);
        if ($request->get('order', '') == '') {
            $order = 'DESC';
        }
        $field = 'created_at';
        $UserBillServices = new UserBillServices();
        if (!isset($where['created_at'])) {
            $where['created_at'][0] = strtotime('-7 days');
            $where['created_at'][1] = time();
        } else {
            $where['created_at'][0] = strtotime($where['created_at'][0]);
            $where['created_at'][1] = strtotime($where['created_at'][1]);
        }
        if ($where['created_at'][1] - $where['created_at'][0] > (3600 * 24 * 60)) {
            return $this->json(1, '时间范围不能超过60天');
        }
        $username = $request->get('username', '');
        if (!empty($username)) {
            $ids = UserModel::where('username', 'like', '%' . $username . '%')->column('id');
            if (!empty($ids)) {
                $where['user_id'][0] = 'in';
                $where['user_id'][1] = $ids;
            }
            unset($where['username']);
        }
        $methods = [
            'select' => 'formatSelect',
            'tree' => 'formatTree',
            'table_tree' => 'formatTableTree',
            'normal' => 'formatNormal',
        ];
        [$items, $total] = $UserBillServices->getBillList($where, $field, $order, $page, $limit);
        foreach ($items as &$item) {
            $item['user_info'] = UserServices::getUserInfo($item['user_id']);
            //钱包类型
            $item['type_str'] = UserBillServices::$TYPE_NAMES[$item['type']];
            //详情类型
            $item['detail_type_str'] = UserBillServices::$DETAIL_TYPE_NAMES[$item['detail_type']];
            $item['created_at'] = date("Y-m-d H:i:s", $item['created_at']);
        }
        // TODO: Change the autogenerated stub
        return call_user_func([$this, $methods[$format]], $items, $total);
    }

    /**
     * 浏览
     * @return Response
     * @throws Throwable
     */
    public function index(): Response
    {
        return raw_view('userbill/index');
    }

    /**
     * 插入
     * @param Request $request
     * @return Response
     * @throws Throwable
     */
    public function insert(Request $request): Response
    {
        if ($request->method() === 'POST') {
            $user_id = $request->post('user_id', '');
            $money = $request->post('money', 0);
            $change = $request->post('change', UserBillServices::CHANGE_ADD);
            $detail_type = $request->post('detail_type', 0);
            $type = $request->post('type', UserBillServices::TYPE_USER);
            $title = UserBillServices::$DETAIL_TYPE_NAMES[$detail_type];
            $admin_info = admin();
            $remark = $request->post('remark', '');
            $remarks = $remark . "(" . $admin_info['id'] . " / " . $admin_info['username'] . ")";
            $data = UserBillServices::addUserBill($user_id, $money, $change, $title, $remarks, $type, $detail_type, $admin_info['id']);
            return json($data);
        }
        $user_id = $request->get('user_id', '');
        return raw_view('userbill/insert', ['user_id' => $user_id]);
    }

    /**
     * 删除
     * @param Request $request
     * @return Response
     * @throws \Exception
     */
    public function delete(Request $request): Response
    {
        $number = $request->post('number');
        if (!empty($number)) {
            if (is_array($number)) {
                $ids = $number;
            } else {
                $ids = [$number];
            }
        }
        if (empty($ids)) {
            return $this->json(1, '请选择要删除的项');
        }
        $UserBillServices = new UserBillServices();
        foreach ($ids as $number) {
            $day = substr($number, 0, 6);
            $id = substr($number, 6);
            $UserBillServices->delBills($id, $day); // TODO: Change the autogenerated stub
        }
        return $this->json(0);
    }
}
