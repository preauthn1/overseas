    }

    /**
     * 插入
     * @param Request $request
     * @return Response
     * @throws BusinessException|Throwable
     */
    public function insert(Request $request): Response
    {
        if ($request->method() === 'POST') {
            $params = $request->post();
            $data_json = UserServices::addUser($params);
            return json($data_json);
        }
        return raw_view('user/insert');
    }

    /**
     * 更新
     * @param Request $request
     * @return Response
     * @throws BusinessException|Throwable
     */
    public function update(Request $request): Response
    {
        if ($request->method() === 'POST') {
            [$id, $data] = $this->updateInput($request);
            if (isset($data['security_code'])) {
                if ($data['security_code'] === '') {
                    unset($data['security_code']);
                } else {
                    $data['security_code'] = Util::passwordHash($data['security_code']);
                }
            }
            $this->doUpdate($id, $data);
            return $this->json(0);
        }
        return raw_view('user/update');
    }

