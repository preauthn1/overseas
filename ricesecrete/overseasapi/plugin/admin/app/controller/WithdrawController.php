<?php

namespace plugin\admin\app\controller;

use app\model\user\UserModel;
use app\model\WithdrawModel;
use app\services\UserServices;
use app\services\WithdrawServices;
use plugin\admin\app\model\Admin;
use plugin\admin\app\model\PaymentPlatform;
use plugin\admin\app\model\User;
use support\exception\BusinessException;
use support\Request;
use support\Response;
use Throwable;

/**
 * 提现管理
 */
class WithdrawController extends Crud
{

    /**
     * @var User
     */
    protected $model = null;

    /**
     * 构造函数
     * @return void
     */
    public function __construct()
    {
        $this->model = new WithdrawModel();
    }

    /**
     * 查询
     * @param Request $request
     * @return Response
     */
    public function select(Request $request): Response
    {
        [$where, $format, $limit, $field, $order] = $this->selectInput($request);
        if ($request->get('order', '') == '') {
            $order = 'desc';
        }
        if (empty($field)) {
            $field = "id";
        }
        $username = $request->get('username', '');
        if (!empty($username)) {
            $ids = UserModel::where('username', 'like', '%' . $username . '%')->column('id');
            if (!empty($ids)) {
                $where['user_id'][0] = 'in';
                $where['user_id'][1] = $ids;
            } else {
                $where['user_id'] = 0;
            }
            unset($where['username']);
        }
        $query = $this->doSelect($where, $field, $order);
        $methods = [
            'select' => 'formatSelect',
            'tree' => 'formatTree',
            'table_tree' => 'formatTableTree',
            'normal' => 'formatNormal',
        ];
        $paginator = $query->paginate($limit);
        $total = $paginator->total();
        $items = $paginator->items();
        $payment_platform = PaymentPlatform::where('id', '>', 0)->field('id,name')->select();
        $payment_platform = array_column($payment_platform->toArray(), null, 'id');
        foreach ($items as &$item) {
            $user_info = [
                'id' => 0,
                'username' => '未知',
            ];
            $item['user_info'] = empty($item['user_id']) ? $user_info : UserModel::where('id', $item['user_id'])->field(['id', 'username', 'mobile_code', 'tree', 'login_type'])->find();
            $tree = $item['user_info']['tree'];
            //去除数组中的空元素
            $tree_arr = array_filter(explode('/', $tree));
            //去掉最后一个元素
            array_pop($tree_arr);
            for ($i = 0; $i <= 1; $i++) {
                $item['user_info']['leader' . $i . '_user'] = "-/-";
            }
            if (!empty($tree_arr)) {
                //获取第一个元素
                $first_element = array_shift($tree_arr);
                $item['user_info']['leader0_user'] = UserServices::getInvUser($first_element);
                $tree_arr = array_reverse($tree_arr);
                if (isset($tree_arr[1])) {
                    $item['user_info']['leader' . 1 . '_user'] = UserServices::getInvUser($tree_arr[1]);
                }
            }
            $item['status_str'] = WithdrawServices::$STATUS_NAME[$item['status']];
            $item['success_time_str'] = empty($item['success_time']) ? '--' : date('Y-m-d H:i:s', $item['success_time']);
            $item['admin_name'] = "";
            if (!empty($item['admin_id'])) {
                $item['admin_name'] = Admin::where('id', $item['admin_id'])->value('username');
            }
            $item['platform_name'] = isset($payment_platform[$item['platform_id']]) ? $payment_platform[$item['platform_id']]['name'] : '';
        }
        // TODO: Change the autogenerated stub
        return call_user_func([$this, $methods[$format]], $items, $total);
    }

    /**
     * 浏览
     * @return Response
     * @throws Throwable
     */
    public function index(): Response
    {
        return raw_view('withdraw/index');
    }

    /**
     * 插入
     * @param Request $request
     * @return Response
     * @throws BusinessException|Throwable
     */
    public function insert(Request $request): Response
    {
        if ($request->method() === 'POST') {
            return $this->json(0, 'ok', ['id' => 0]);
        }
        return raw_view('withdraw/insert');
    }

    /**
     * 更新
     * @param Request $request
     * @return Response
     * @throws BusinessException|Throwable
     */
    public function update(Request $request): Response
    {
        if ($request->method() === 'POST') {
            [$id, $data] = $this->updateInput($request);
            $status = WithdrawModel::where('id', $id)->value('status');
            if ($status == WithdrawServices::STATUS_SUCCESS) {
                return $this->json(1, '请勿重复操作');
            }
            $remark = $request->post('remark', '');
            if (empty($remark)) {
                return $this->json(1, '请填备注原因');
            }
            if ($data['status'] == 2 && $status == WithdrawServices::STATUS_WAIT) {
                $number = $data['number'];
                $ret = WithdrawServices::successWithdraw($number, $remark);
                if ($ret) {
                    return $this->json(0);
                } else {
                    return $this->json(1, '操作失败');
                }
            }
            if ($data['status'] == 3 && $status == WithdrawServices::STATUS_WAIT) {
                $number = $data['number'];
                WithdrawServices::refuseWithdraw($number, $remark);
            }
            WithdrawServices::waitWithdrawUpdate();
            return $this->json(0);
        }
        return raw_view('withdraw/update');
    }

}
